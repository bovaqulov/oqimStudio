"""A contract, not a unit test: the Python block vocabulary against the TypeScript one.

`apps/flows/vocabulary.py` and
`frontend/src/features/flow-builder/node-definitions.ts::NODE_TYPE_DEFINITIONS`
are two copies of one enumeration. The editor draws from the second and a new
block type is always added there first — the compiler enforces that much, since
the table is `Record<NodeType, NodeTypeDefinition>`. Nothing enforces the first,
and the moment the two disagree the backend starts refusing graphs the editor
can draw, or accepting edges the runtime cannot walk. This file is the thing
that notices.

**When it fails.** It is telling you that somebody changed the editor's block
table and the backend has not caught up. Do not edit this file to make it pass
and do not weaken the parser. Open `node-definitions.ts`, read what changed, and
make the same change in `vocabulary.py`:

- *a type in the editor and not here* — add a `BlockType` row. Then walk
  `.claude/skills/oqim-blok/SKILL.md`: a type the backend has no handler for is
  stepped over silently, which is a block that does nothing in front of a paying
  customer.
- *a type here and not in the editor* — the block was removed or renamed.
  Deleting the row here is only half of it; graphs already saved still carry the
  old string, so decide what happens to them before you delete anything.
- *the ports disagree* — the editor moved an exit. Every stored edge leaving the
  old port is now an edge nothing walks (`walk` asks
  `flow.next_node_id(id, port)` and gets None), so this is the failure that
  costs conversations rather than saves.

It reads the TypeScript with regular expressions rather than by running `tsc`,
deliberately: the backend test suite must not need Node, a toolchain or an
`npm install` to run — the whole point of `TELEGRAM_OFFLINE` is that this side
can be driven on its own. A parse that cannot find the table at all fails loudly
rather than quietly asserting nothing, which is the one way a contract test can
be worse than no test.

The check is limited to **the set of types and each one's fixed ports**. The
button and back ports are derived from a node's own contents on both sides and
there is no table to compare; the geometry, colours and `hasX` flags are the
canvas's business and the backend has no opinion about them.

"A node's own contents" includes what the block *sends*: a keyboard Telegram
will not carry publishes no exits at all, so `vocabulary.published_ports` and
`node-definitions.ts` both read the content kind before the buttons and the
back row — `routable_buttons` / `nodeButtons` for the keys, `BUTTONLESS_CONTENT`
/ `backRowReachesTelegram` for the row. Adding a content kind that takes no
`reply_markup` is therefore a change to both halves and not just to
`sender.CONTENT_METHODS`. `ContentKindContractTests` below holds the other pair
— which block types overrule the stored `contentKind` — together.
"""

from __future__ import annotations

import re
from pathlib import Path

from django.test import SimpleTestCase

from apps.engine.sender import TYPE_CONTENT_KINDS
from apps.flows.vocabulary import NODE_TYPES

#: `backend/apps/flows/` -> repo root -> the editor's table.
DEFINITIONS_PATH = (
    Path(__file__).resolve().parents[3] / "frontend" / "src" / "features" / "flow-builder" / "node-definitions.ts"
)

#: The three helpers that stand in for a fixed port list, and what each one
#: publishes unconditionally. Written out here rather than parsed out of the
#: helper bodies because the bodies are geometry — offsets, clamps, the card's
#: corner radius — and the only part of them this contract is about is which
#: port ids come out.
#:
#: A *new* helper appearing in the table is not something this can guess at, so
#: `_ports_of` refuses rather than assuming: an unrecognised `ports:` value is a
#: failure naming the helper, which is exactly the moment somebody has to decide
#: what the backend does with it.
PORT_HELPERS: dict[str, tuple[str, ...]] = {
    "singleOutPort": ("out",),
    # out + one port per routable button + `back` when the block carries one.
    "keyboardPorts": ("out",),
    "noPorts": (),
    # paid/cancelled + the same button and back ports a keyboard block has.
    "invoicePorts": ("paid", "cancelled"),
    "subscriptionPorts": ("subscribed", "not_subscribed"),
}

#: `branchPorts(node, height, { id: "yes", ... }, { id: "no", ... })` written
#: inline in the table, which is how `condition` and `script` declare their pair.
INLINE_BRANCH = re.compile(
    r"branchPorts\(\s*node,\s*_?\w+,\s*\{\s*id:\s*\"(?P<first>[^\"]+)\".*?\}\s*,\s*\{\s*id:\s*\"(?P<second>[^\"]+)\"",
    re.DOTALL,
)

#: `triplePorts(node, height, [ {id: …}, {id: …}, {id: …} ])` — the same
#: inline shape for a block with three exits, which «AI agent» is the first of.
#: Read with one pattern applied repeatedly rather than three capture groups:
#: the ids are what this contract is about and their order is the card's
#: drawing order, so a list is exactly the right thing to collect.
INLINE_TRIPLE = re.compile(r"triplePorts\(\s*node,\s*_?\w+,\s*\[(?P<body>.*?)\]\s*\)", re.DOTALL)
PORT_ID = re.compile(r"\{\s*id:\s*\"(?P<id>[^\"]+)\"")

#: One `<type>: {` at the table's own indentation. The table is a flat object
#: literal of two-space entries, so anchoring on the indent is what keeps a
#: nested `rating: {` inside some block's config from reading as a block type.
#:
#: The optional quotes are not a loosening. A block type may carry a dot —
#: `agent.ask` is the first, and it is namespaced because asking is one thing
#: an agent does and classifying is another — and a dotted key is not a valid
#: bare identifier, so TypeScript requires it to be written `"agent.ask": {`.
#: Refusing to read the quotes would mean this contract silently stopped
#: covering exactly the type most likely to be added next, which is the one way
#: a contract test can be worse than none.
ENTRY = re.compile(r"^  \"?(?P<type>[a-z][a-zA-Z0-9_.]*)\"?:\s*\{$", re.MULTILINE)

#: The `ports:` line of one entry, up to the end of that entry's value.
PORTS = re.compile(r"^    ports:\s*(?P<value>.*?),?\n  \},", re.MULTILINE | re.DOTALL)


def _table_source(source: str) -> str:
    """The body of `NODE_TYPE_DEFINITIONS`, from its opening brace to the
    closing `};` at column zero."""
    start = source.index("export const NODE_TYPE_DEFINITIONS")
    body_start = source.index("{", start)
    end = source.index("\n};", body_start)
    return source[body_start : end + 1]


def _entries(table: str) -> dict[str, str]:
    """Each block type in the table, mapped to the source of its definition."""
    found: dict[str, str] = {}
    matches = list(ENTRY.finditer(table))
    for index, match in enumerate(matches):
        stop = matches[index + 1].start() if index + 1 < len(matches) else len(table)
        found[match.group("type")] = table[match.start() : stop]
    return found


def _ports_of(node_type: str, entry_source: str) -> tuple[str, ...]:
    """The fixed ports one entry declares, in the order the card draws them."""
    match = PORTS.search(entry_source)
    if match is None:
        raise AssertionError(f"«{node_type}» yozuvida `ports:` topilmadi — {DEFINITIONS_PATH} o'zgargan")
    value = match.group("value").strip()

    named = PORT_HELPERS.get(value)
    if named is not None:
        return named

    branch = INLINE_BRANCH.search(value)
    if branch is not None:
        return (branch.group("first"), branch.group("second"))

    triple = INLINE_TRIPLE.search(value)
    if triple is not None:
        return tuple(match.group("id") for match in PORT_ID.finditer(triple.group("body")))

    raise AssertionError(
        f"«{node_type}» bloki `ports` uchun tanish bo'lmagan qiymat ishlatyapti: {value!r}. "
        "PORT_HELPERS ga qo'shing va apps/flows/vocabulary.py dagi portlarni yangilang."
    )


class NodeVocabularyContractTests(SimpleTestCase):
    """The editor's block table, read from the source, against `vocabulary.py`."""

    @classmethod
    def setUpClass(cls) -> None:
        super().setUpClass()
        cls.entries = _entries(_table_source(DEFINITIONS_PATH.read_text(encoding="utf-8")))

    def test_the_table_was_actually_found(self):
        """The guard on everything below.

        A regex that matched nothing would let every other assertion in this
        file pass against an empty dict — a contract test that has quietly
        stopped testing is worse than none, because it is still on the board.
        Twelve is not a target; it is a floor that says the parse worked. The
        table held twenty-four before «Menyu», «Savol», «Kanalga obuna»,
        «Baho / NPS», «AI agent», «Kod» and «Operatorga» were removed.
        """
        self.assertGreaterEqual(
            len(self.entries), 12, f"{DEFINITIONS_PATH} dan blok jadvali o'qilmadi — regexlarni tekshiring"
        )

    def test_both_sides_know_the_same_block_types(self):
        editor = set(self.entries)
        backend = set(NODE_TYPES)

        self.assertEqual(
            editor,
            backend,
            "Blok turlari mos kelmadi. Muharrirda bor, backendda yo'q: "
            f"{sorted(editor - backend)}; backendda bor, muharrirda yo'q: {sorted(backend - editor)}. "
            "apps/flows/vocabulary.py ni tuzating — bu faylni emas.",
        )

    def test_each_block_publishes_the_same_fixed_ports(self):
        for node_type, entry_source in sorted(self.entries.items()):
            block = NODE_TYPES.get(node_type)
            if block is None:
                continue  # already reported, by name, in the test above
            with self.subTest(node_type):
                self.assertEqual(
                    _ports_of(node_type, entry_source),
                    block.ports,
                    f"«{node_type}» bloki chiqishlari mos kelmadi. Saqlangan grafiklardagi eski portdan "
                    "ketayotgan bog'lanishlarni endi hech narsa yurmaydi.",
                )

    def test_the_entry_blocks_are_the_same_six(self):
        """`node-registry.ts::ENTRY_NODE_TYPES` against `vocabulary.ENTRY_TYPES`.

        Its own assertion because the consequence is its own: an ordinary block
        in the entry set gets a `FlowTrigger` derived from it, defaulting to a
        catch-all that answers *every* message the bot receives — and an entry
        block missing from it is delivered to the customer as a message carrying
        its card explanation.
        """
        registry = (DEFINITIONS_PATH.parent / "node-registry.ts").read_text(encoding="utf-8")
        match = re.search(r"const ENTRY_NODE_TYPES: NodeType\[\] = \[(?P<body>.*?)\];", registry, re.DOTALL)
        self.assertIsNotNone(match, "node-registry.ts dan ENTRY_NODE_TYPES o'qilmadi")

        editor = set(re.findall(r"\"([a-z]+)\"", match.group("body")))
        backend = {name for name, block in NODE_TYPES.items() if block.entry}

        self.assertEqual(
            editor,
            backend,
            f"Boshlanish bloklari mos kelmadi: muharrirda {sorted(editor)}, backendda {sorted(backend)}",
        )

    def test_the_flow_owned_entry_blocks_are_the_same_two(self):
        """`OWNED_ENTRY_TYPES` — the ones `applyEntryRule` keeps one of and
        deletes the rest of on load. The import validator refuses a graph
        carrying two, so a type added there and not here is a graph accepted and
        then silently trimmed the first time somebody opens it."""
        registry = (DEFINITIONS_PATH.parent / "node-registry.ts").read_text(encoding="utf-8")
        match = re.search(r"const OWNED_ENTRY_TYPES: NodeType\[\] = \[(?P<body>.*?)\];", registry, re.DOTALL)
        self.assertIsNotNone(match, "node-registry.ts dan OWNED_ENTRY_TYPES o'qilmadi")

        editor = set(re.findall(r"\"([a-z]+)\"", match.group("body")))
        backend = {name for name, block in NODE_TYPES.items() if block.owns_entry}

        self.assertEqual(editor, backend, f"Oqimga tegishli boshlanish bloklari: {sorted(editor)} / {sorted(backend)}")


#: The editor's copy of `sender.TYPE_CONTENT_KINDS`, in
#: `flow-builder/lib/message-content.ts`.
CONTENT_KIND_TABLE = re.compile(
    r"const TYPE_CONTENT_KINDS: Partial<Record<FlowNode\[\"type\"\], MessageContentKind>> = \{"
    r"(?P<body>.*?)\n\};",
    re.DOTALL,
)
CONTENT_KIND_ROW = re.compile(r"^\s*(?P<type>[a-z][a-zA-Z0-9_]*):\s*\"(?P<kind>[a-z]+)\",", re.MULTILINE)


class ContentKindContractTests(SimpleTestCase):
    """Which blocks answer for themselves about what they send.

    `sender.content_kind` is what picks the Bot API method, so the runtime is
    the side that decides; the editor needs the same answer to draw the right
    content panel, ask for the right file and validate the right field.

    **When it fails.** The two tables disagree. The editor's copy is the one to
    move unless the runtime is what changed — and check the direction, because
    the halves fail differently: a type the *editor* is missing means a block
    converted out of Xabar keeps that block's `contentKind`, so the panel asks
    for a photo, the validator demands one, and what actually goes out is a
    text message with a keyboard. That was true of `subscription`, `rating`,
    `language` and `followup` for as long as the editor's table held only two
    rows, and nothing anywhere said so.
    """

    @classmethod
    def setUpClass(cls) -> None:
        super().setUpClass()
        source = (DEFINITIONS_PATH.parent / "lib" / "message-content.ts").read_text(encoding="utf-8")
        match = CONTENT_KIND_TABLE.search(source)
        cls.found = match is not None
        cls.editor = dict(CONTENT_KIND_ROW.findall(match.group("body"))) if match else {}

    def test_the_table_was_actually_found(self):
        self.assertTrue(self.found, "message-content.ts dan TYPE_CONTENT_KINDS o'qilmadi — regexni tekshiring")
        self.assertGreaterEqual(len(self.editor), 2, "jadval bo'sh o'qildi")

    def test_both_sides_force_the_same_blocks(self):
        self.assertEqual(
            set(self.editor),
            set(TYPE_CONTENT_KINDS),
            "muharrir va runtime bir xil bloklarni majburlashi kerak "
            "(message-content.ts ↔ apps/engine/sender.py)",
        )

    def test_they_force_it_to_the_same_thing(self):
        for node_type, kind in sorted(TYPE_CONTENT_KINDS.items()):
            with self.subTest(node_type):
                self.assertEqual(self.editor.get(node_type), kind)

    def test_every_forced_type_is_a_block_that_exists(self):
        """A row for a type nobody can draw is a rule guarding nothing."""
        self.assertLessEqual(set(TYPE_CONTENT_KINDS), set(NODE_TYPES))
