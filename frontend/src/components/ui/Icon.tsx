// Only the type travels back out of this module: re-exporting the guard would
// hand every server caller a client reference again, which is the bug this
// split exists to fix. Import `isIconName` from "./icon-names" directly.
export type { IconName } from "./icon-names";

export function Icon({
  name,
  size = 16,
  weight = "regular",
  className,
  style,
}: {
  name: IconName;
  size?: number;
  weight?: IconWeight;
  className?: string;
  style?: CSSProperties;
}) {
  const Component = registry[name];
  /*
   * Decorative, every one of them.
   *
   * Nothing in this product uses an icon as the only carrier of meaning: a row
   * that shows one also spells the label beside it, and a control that shows
   * only an icon names itself (`IconButton` takes `label`, the tab bar and the
   * nav rows carry `aria-label` and `title`). So the svg has nothing to add to
   * an accessible name and, unmarked, is one more node a screen reader and an
   * audit tool both have to decide about — three separate reports of "link with
   * no accessible name" landed on links whose text was right there beside an
   * unmarked icon.
   */
  return <Component size={size} weight={weight} className={className} style={style} aria-hidden />;
}
