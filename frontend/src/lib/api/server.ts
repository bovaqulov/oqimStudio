import "server-only";
import { cookies } from "next/headers";

/**
 * The server-side seam to the Django backend.
 *
 * Every repository under `features/<area>/data` calls through here, and only
 * here: one place knows the base URL, how a request is authenticated, which tenant
 * it acts on, and what an error looks like coming back.
 *
 * Server-only on purpose. The credential is an httpOnly cookie the browser
 * cannot read, so a fetch from a client component could not authenticate even
 * if one were written — which is the point.
 */

/** Set in `.env`; the Next server talks to Django directly, not through the browser. */
export const API_BASE_URL = (process.env.API_BASE_URL ?? "http://127.0.0.1:8000").replace(/\/$/, "");

/** The DRF token, httpOnly — this is the actual credential. */
export const TOKEN_COOKIE = "oqim_token";
/** Which tenant the reader is looking at. Set by the workspace switcher. */
export const WORKSPACE_COOKIE = "oqim_ws";

export class ApiError extends Error {
  constructor(
    message: string,
    readonly status: number,
    /** Stable code from the backend — the same vocabulary as `AuthErrorCode`. */
    readonly code: string = "server_error",
    /** Input the message belongs under, when it is about one field. */
    readonly field?: string,
  ) {
    super(message);
    this.name = "ApiError";
  }

  get isNotFound(): boolean {
    return this.status === 404;
  }

  /** The backend never answered — not the same thing as it answering with an error. */
  get isUnreachable(): boolean {
    return this.code === "backend_unreachable";
  }
}

/** How long a single backend call may take before it is treated as down. */
const REQUEST_TIMEOUT_MS = 20_000;

/** Shown to the reader, so it is written for one — not "ECONNREFUSED". */
export const BACKEND_UNREACHABLE_MESSAGE =
  "Server bilan bog'lanib bo'lmadi. U qayta ishga tushayotgan bo'lishi mumkin — bir necha soniyadan keyin qayta urinib ko'ring.";

export type QueryParams = Record<string, string | number | boolean | null | undefined>;

function buildUrl(path: string, params?: QueryParams): string {
  const search = new URLSearchParams();
  for (const [key, value] of Object.entries(params ?? {})) {
    if (value === null || value === undefined || value === "") continue;
    search.set(key, String(value));
  }
  const query = search.toString();
  return `${API_BASE_URL}${path}${query ? `?${query}` : ""}`;
}

export async function readAuthToken(): Promise<string | null> {
  return (await cookies()).get(TOKEN_COOKIE)?.value ?? null;
}

interface RequestOptions {
  /** Tenant this call acts on. Repositories always know it, so they always pass it. */
  workspaceId?: string;
  params?: QueryParams;
  body?: unknown;
  /**
   * A file going the other way. Sent as-is, with no `Content-Type` of our own:
   * a multipart boundary is generated by `fetch` and stating the header by hand
   * omits it, which is a request the server cannot parse at all.
   */
  form?: FormData;
  method?: "GET" | "POST" | "PATCH" | "PUT" | "DELETE";
  /** Bearer token to use instead of the cookie — the sign-up flow has no cookie yet. */
  token?: string | null;
}

/**
 * One request. Errors arrive as `ApiError` carrying the backend's own code, so
 * a caller can tell "nothing found" from "you may not" without parsing text.
 */
export async function apiRequest<T>(path: string, options: RequestOptions = {}): Promise<T> {
  const token = options.token !== undefined ? options.token : await readAuthToken();
  const headers: Record<string, string> = { Accept: "application/json" };
  if (token) headers.Authorization = `Token ${token}`;
  if (options.workspaceId) headers["X-Workspace-Id"] = options.workspaceId;
  if (options.body !== undefined) headers["Content-Type"] = "application/json";

  let response: Response;
  try {
    response = await fetch(buildUrl(path, options.params), {
      method: options.method ?? "GET",
      headers,
      body: options.form ?? (options.body === undefined ? undefined : JSON.stringify(options.body)),
      // Tenant data is never shared between readers, so nothing here is cacheable.
      cache: "no-store",
      // A backend that accepts the connection and then says nothing would
      // otherwise hold the page open until the browser gives up.
      signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
    });
  } catch {
    // Connection refused, DNS gone, timed out — the backend is not answering
    // at all. Callers get the same typed error as any other failure so a page
    // can say which of the two happened; without this it arrives as a bare
    // TypeError and every screen reports "unexpected error".
    throw new ApiError(BACKEND_UNREACHABLE_MESSAGE, 503, "backend_unreachable");
  }

  if (response.status === 204) return undefined as T;

  const text = await response.text();
  const payload = text ? safeParse(text) : null;

  if (!response.ok) {
    const error = (payload as { error?: { code?: string; message?: string; field?: string } } | null)?.error;
    throw new ApiError(
      error?.message || `So'rov ${response.status} bilan yakunlandi`,
      response.status,
      error?.code ?? "server_error",
      error?.field,
    );
  }
  return payload as T;
}

function safeParse(text: string): unknown {
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

/** DRF paginates lists; every repository wants the rows. */
interface Paginated<T> {
  count: number;
  results: T[];
}

export async function apiList<T>(path: string, options: RequestOptions = {}): Promise<T[]> {
  const payload = await apiRequest<T[] | Paginated<T>>(path, options);
  return Array.isArray(payload) ? payload : (payload?.results ?? []);
}

/**
 * A read whose "missing" answer is `undefined` rather than a thrown error —
 * the shape every `getById` in this codebase is written against.
 */
export async function apiFind<T>(path: string, options: RequestOptions = {}): Promise<T | undefined> {
  try {
    return await apiRequest<T>(path, options);
  } catch (error) {
    if (error instanceof ApiError && error.isNotFound) return undefined;
    throw error;
  }
}
